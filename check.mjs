import { readFile, access } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve('dist');
const html = await readFile(path.join(root, 'index.html'), 'utf8');
const js = await readFile(path.join(root, 'app.js'), 'utf8');
const css = await readFile(path.join(root, 'styles.css'), 'utf8');
const fonts = await readFile(path.join(root, 'fonts.css'), 'utf8');
const headers = await readFile(path.join(root, '_headers'), 'utf8');
const server = await readFile('server.mjs', 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, 'IDs must be unique');
for (const match of html.matchAll(/\bhref="#([^"]+)"/g)) assert(ids.includes(match[1]), `Unknown anchor ${match[1]}`);
for (const match of html.matchAll(/\b(?:src|href)="(\.\/[^"#]+)"/g)) await access(path.resolve(root, match[1]));
for (const match of fonts.matchAll(/url\((\.\/[^)]+)\)/g)) await access(path.resolve(root, match[1]));
for (const match of js.matchAll(/image: '([^']+)'/g)) await access(path.join(root,'assets',match[1]));
assert(!/\bon\w+\s*=/i.test(html), 'Inline event handlers are not permitted');
assert(!/<script(?![^>]*\bsrc=)[^>]*>/i.test(html), 'Inline scripts are not permitted');
assert(!/\b(innerHTML|outerHTML|eval|insertAdjacentHTML|localStorage|sessionStorage)\b/.test(js), 'Unsafe sinks/storage are not permitted');
assert(!/\bfetch\s*\(/.test(js), 'No external data transmission is expected');
for (const match of html.matchAll(/<a\b[^>]*target="_blank"[^>]*>/g)) assert(/rel="noopener noreferrer"/.test(match[0]), 'External tabs require rel protection');
assert(html.includes("object-src 'none'") && html.includes("base-uri 'none'") && html.includes("form-action 'none'"), 'CSP is required');
const mapFrames = [...html.matchAll(/<iframe\b[^>]*>/g)].map(match => match[0]);
assert.equal(mapFrames.length, 1, 'Exactly one map iframe is expected');
assert(mapFrames[0].includes('src="https://widgets.2gis.com/widget?') && mapFrames[0].includes('loading="lazy"') && mapFrames[0].includes('sandbox='), 'The 2GIS widget must be lazy-loaded and sandboxed');
for (const policy of [html, headers, server]) assert(policy.includes('frame-src https://widgets.2gis.com'), 'CSP must only allow the 2GIS frame');
assert(css.includes('prefers-reduced-motion:reduce'), 'Reduced-motion support is required');
assert.equal((html.match(/<h1\b/g) || []).length, 1, 'Exactly one H1 is required');
console.log('PASS: local assets, anchors, unique IDs, CSP, external links, script safety, reduced motion and heading structure.');
